import test from 'node:test';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
import { parseCulqiEventResource, verifyCulqiEventIdentity } from '../../../src/lib/payments/verification.ts';

// Offline reproduction of exact historical source, with no provider connection. IDs/references are deliberately synthetic.
// The observed amount/date/field names are evidence of shape, not a provider
// response generated by this script. There is no real provider or database.
const chargeId = 'chr_test_OFFLINEDirectCharge01';
const eventId = 'evt_test_OFFLINEEnvelope01';
const camel = { object: 'charge', id: chargeId, creationDate: 1792122606744,
  amount: 12300, amountRefunded: 0, currentAmount: 12300, currencyCode: 'PEN',
  description: 'Bagelito batch - BAG-OFFLINE-008',
  outcome: { type: 'venta_exitosa', code: 'AUT0000' }, capture: true,
  captureDate: 1792122606744, duplicated: false,
  metadata: { bagelito_order_code: 'BAG-OFFLINE-008' }, paid: false };
const snake = { object: 'charge', id: chargeId, creation_date: 1792122606744,
  amount: 12300, amount_refunded: 0, current_amount: 12300, currency_code: 'PEN',
  capture: true, capture_date: 1792122606744, duplicated: false,
  outcome: { type: 'venta_exitosa', code: 'AUT0000' },
  metadata: { bagelito_order_code: 'BAG-OFFLINE-008' }, paid: false };
const versions = JSON.parse(await readFile(new URL('./versions.json', import.meta.url), 'utf8'));
const repository = fileURLToPath(new URL('../../../', import.meta.url));
const currentVerification = await readFile(new URL('../../../src/lib/payments/verification.ts', import.meta.url), 'utf8');
const digest = (source) => createHash('sha256').update(source).digest('hex');

for (const version of versions) {
  const source = execFileSync('git', ['show', `${version.sha}:${version.source_path}`], { cwd: repository, encoding: 'utf8' });
  const verification = execFileSync('git', ['show', `${version.sha}:${version.verification_path}`], { cwd: repository, encoding: 'utf8' });
  assert.equal(digest(source), version.source_sha256);
  assert.equal(digest(verification), version.verification_sha256);
  assert.equal(digest(currentVerification), version.verification_sha256);
  const body = stripTypeScriptTypes(source.replace(/^import .*;\n/gm, '')).replace(/export /g, '');
  const load = new Function('NextResponse', 'fetchCulqiEvent', 'isCulqiRequestAllowed',
    'createSupabaseAdminClient', 'parseCulqiEventResource', 'verifyCulqiEventIdentity', 'console',
    `${body}; return POST;`);
  async function execute(requestBody, upstream400 = false) {
    const lookups = [], clients = [], rpc = [], logs = [];
    const post = load({ json: (payload, init = {}) => ({ payload, status: init.status ?? 200 }) },
      async (id) => {
        lookups.push(id);
        if (upstream400) throw Object.assign(new Error('offline provider failure'), {
          status: 400, errorType: 'parameter_error', eventModeMatchesConfig: true,
        });
        return { id: eventId, type: 'charge.creation.succeeded', data: snake };
      }, () => true, () => {
        clients.push('mock_client');
        return { rpc: async (name, args) => { rpc.push({ name, args }); return { data: { status: 'paid' }, error: null }; } };
      }, parseCulqiEventResource, verifyCulqiEventIdentity,
      { info: (...args) => logs.push(args), error: () => assert.fail('raw error log'), warn: () => assert.fail('raw warning') });
    const response = await post(new Request('https://fixture.invalid/api/webhooks/culqi', {
      method: 'POST', body: JSON.stringify(requestBody),
    }));
    return { response, lookups, clients, rpc, diagnostic: logs[0][1] };
  }
  for (const [shape, payload] of [['panel_camel_charge', camel], ['api_snake_charge', snake]]) {
    test(`${version.label}: ${shape} cannot be queried as an event or settle`, async () => {
      const r = await execute(payload);
      assert.equal(r.response.status, 400);
      assert.equal(r.diagnostic.stage, 'request');
      assert.equal(r.diagnostic.reason, 'invalid_event_id');
      assert.equal(r.diagnostic.upstreamHttpStatus, null);
      assert.deepEqual(r.lookups, []);
      assert.deepEqual(r.clients, []);
      assert.deepEqual(r.rpc, []);
      assert.equal(r.diagnostic.eventVerified, false);
      assert.equal(r.diagnostic.transactionAttempted, false);
    });
  }
  test(`${version.label}: a synthetic event reference reaches only its independently verified resource`, async () => {
    const r = await execute({ id: eventId, data: camel, type: 'caller_claim_is_ignored' });
    assert.equal(r.response.status, 200);
    assert.deepEqual(r.lookups, [eventId]);
    assert.equal(r.rpc.length, 1);
    assert.equal(r.rpc[0].args.p_event_type, 'charge.creation.succeeded');
    assert.deepEqual(r.rpc[0].args.p_resource, snake);
  });
  test(`${version.label}: synthetic event lookup400 reproduces the500 classification`, async () => {
    const r = await execute({ id: eventId }, true);
    assert.equal(r.response.status, 500);
    assert.deepEqual(r.response.payload, { ok: false, error: 'Could not process Culqi webhook.' });
    assert.deepEqual(r.lookups, [eventId]);
    assert.equal(r.diagnostic.stage, 'event_lookup');
    assert.equal(r.diagnostic.upstreamHttpStatus, 400);
    assert.equal(r.diagnostic.upstreamErrorType, 'parameter_error');
    assert.equal(r.diagnostic.eventVerified, false);
    assert.equal(r.diagnostic.transactionAttempted, false);
    assert.deepEqual(r.clients, []);
    assert.deepEqual(r.rpc, []);
  });
}
